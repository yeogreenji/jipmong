export const SAMPLE_DISTRICTS: string[] = Array.from(
  new Set(SAMPLE_COMPLEXES.map((complex) => complex.district)),
);

export function jeonseRatio(complex: Complex): number {
  if (complex.priceManwon <= 0) return 0;
  return (complex.jeonseManwon / complex.priceManwon) * 100;
}

export function peakDiffPct(complex: Complex): number {
  if (complex.peakPriceManwon <= 0) return 0;
  return ((complex.priceManwon - complex.peakPriceManwon) / complex.peakPriceManwon) * 100;
}

export function findComplex(id: string): Complex | undefined {
  return SAMPLE_COMPLEXES.find((complex) => complex.id === id);
}
